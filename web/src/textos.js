const IDIOMA = (() => {
    try {
        const guardado = localStorage.getItem('language');
        if (['es', 'en', 'pt'].includes(guardado)) return guardado;
    } catch (e) { /* sin almacenamiento */ }
    const nav = (navigator.language || 'en').slice(0, 2);
    return ['es', 'pt'].includes(nav) ? nav : 'en';
})();

